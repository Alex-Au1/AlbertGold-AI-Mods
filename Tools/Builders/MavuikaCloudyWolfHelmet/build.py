"""
MavuikaCloudyWolf / Helmet: hide the motorcycle helmet Mavuika wears while riding her bike.

The helmet is not in GI-Model-Importer-Assets. It was found in the maintainer's frame dump taken while riding
(GIMI/FrameAnalysis-2026-11-17-221506, also in FrameAnalysis-FenrirModRiding-2026-11-17-214513, same hashes):
  - pre-skinning draw 000002 (vs 653c63ba4a73ca8b): position vb 862f9f72, blend vb 93ca98ae, 2 343 vertices,
    a shell round her head (y 1.48 .. 1.82) with two pointed ears;
  - ib 8f86c652, two parts: first index 0 (6 636 indices: the shell; draws 159 170 196 358 369) and first index
    6636 (84 indices, drawn alone in a later pass, draw 353); texcoord vb 2c54dd38.
The mod skips every draw that binds that ib, which hides both parts in every pass (shadow and outline included).

Run:  python build.py [--dump <FrameAnalysis folder>]
Writes the mod to Images/GI/Mavuika/MavuikaCloudyWolf/Helmet/ (where the maintainer asked for it) and a preview
of what is hidden to Testing/Acceptance/Previews/MavuikaCloudyWolfHelmet.png.
"""
import argparse
import glob
import os
import shutil
import sys

import numpy as np

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
sys.path.insert(0, os.path.join(REPO, "Tools", "ModKit"))
from modkit import gimi, render  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(REPO, "Images", "GI", "Mavuika", "MavuikaCloudyWolf", "Helmet")
PREVIEW = os.path.join(REPO, "Testing", "Acceptance", "Previews", "MavuikaCloudyWolfHelmet.png")
DEFAULT_DUMP = r"E:\Computer\Games\Wuthering Waves Mods\Importer\GIMI\FrameAnalysis-2026-11-17-221506"

IB = "8f86c652"
POSITION_VB = "862f9f72"

INI = f"""; MavuikaCloudyWolf / Helmet: hides Mavuika's motorcycle helmet while she rides.
; GENERATED by Tools/Builders/MavuikaCloudyWolfHelmet/build.py; do not edit by hand.

; Every draw of the helmet (both ib parts, every pass) binds this index buffer.
[TextureOverrideMavuikaHelmetIB]
hash = {IB}
handling = skip
"""


def keep_dump(dump):
    """copy the few text files the preview needs next to the recipe, so it builds without the 10 GB dump"""
    mine = os.path.join(HERE, "dump")
    os.makedirs(mine, exist_ok=True)
    want = {"vb0.txt": f"000002-vb0={POSITION_VB}-*.txt"}
    for d in ("159", "353"):
        want[f"ib_{d}.txt"] = f"000{d}-ib={IB}-*.txt"
    for name, pat in want.items():
        dst = os.path.join(mine, name)
        hits = glob.glob(os.path.join(dump, pat)) if dump and os.path.isdir(dump) else []
        if hits:
            shutil.copyfile(hits[0], dst)
        if not os.path.exists(dst):
            sys.exit(f"missing {name}: pass --dump <the riding FrameAnalysis folder>")
    return mine


def preview(mine):
    shell = gimi.load_dump(os.path.join(mine, "vb0.txt"), os.path.join(mine, "ib_159.txt"))
    part2 = gimi.load_dump(os.path.join(mine, "vb0.txt"), os.path.join(mine, "ib_353.txt"))
    pos, nrm = shell["pos"][:, :3], shell["nrm"][:, :3]
    nrm = nrm / np.maximum(np.linalg.norm(nrm, axis=1, keepdims=True), 1e-6)
    tris = [shell["tris"], part2["tris"]]
    cols = [(0.75, 0.75, 0.8), (1.0, 0.45, 0.1)]
    imgs, labels = [], []
    for yaw, name in ((0, "front"), (90, "side"), (180, "back"), (45, "3/4")):
        imgs.append(render.render(pos, nrm, tris, size=(420, 420), yaw=yaw, pitch=10, colors=cols))
        labels.append(f"hidden: helmet {name} (orange = 2nd ib part)")
    os.makedirs(os.path.dirname(PREVIEW), exist_ok=True)
    render.sheet(imgs, cols=4, labels=labels).save(PREVIEW)
    print(f"helmet: {len(pos)} vertices, parts {len(tris[0])} + {len(tris[1])} triangles -> {PREVIEW}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dump", default=DEFAULT_DUMP)
    a = ap.parse_args()
    preview(keep_dump(a.dump))
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "MavuikaCloudyWolfHelmet.ini"), "w", newline="\n") as f:
        f.write(INI)
    print("wrote", os.path.join(OUT, "MavuikaCloudyWolfHelmet.ini"))


if __name__ == "__main__":
    main()
